"""Write THIRD_PARTY_LICENSES: the license texts of every crate, and of the C
libraries vendored by them, that the packaged bigiris binary links."""
import argparse
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'THIRD_PARTY_LICENSES'
# The features and target the distribution packages build.
FEATURES = 'bigiris/gui,bigiris/ai'
TARGET = 'x86_64-unknown-linux-gnu'
LICENSE_PREFIXES = ('LICENSE', 'LICENCE', 'COPYING', 'NOTICE', 'UNLICENSE')
ARCHIVE_SUFFIXES = ('.tar', '.gz', '.xz', '.bz2', '.zst', '.zip')
SKIPPED_DIRS = {'tests', 'test', 'testdata', 'benches', 'examples', 'fuzz', '.git'}


def linked_packages(metadata):
    """Non-workspace packages reached from bigiris through normal dependencies.

    Proc-macro crates run in the compiler and are not linked, so the walk
    stops at them; build-dependencies are skipped for the same reason.
    """
    packages = {p['id']: p for p in metadata['packages']}
    nodes = {n['id']: n for n in metadata['resolve']['nodes']}
    root = next(p['id'] for p in metadata['packages'] if p['name'] == 'bigiris' and p['source'] is None)
    seen, stack = set(), [root]
    while stack:
        for dep in nodes[stack.pop()]['deps']:
            if dep['pkg'] in seen or not any(k['kind'] is None for k in dep['dep_kinds']):
                continue
            if all('proc-macro' in t['kind'] for t in packages[dep['pkg']]['targets']):
                continue
            seen.add(dep['pkg'])
            stack.append(dep['pkg'])
    linked = (packages[i] for i in seen if packages[i]['source'] is not None)
    return sorted(linked, key=lambda p: (p['name'], p['version']))


def is_license_file(path):
    name = path.name.upper()
    return name.startswith(LICENSE_PREFIXES) and not name.lower().endswith(ARCHIVE_SUFFIXES) and path.is_file()


def license_files(package):
    """License files of the package and of the C sources it vendors, outside test data.

    A crate from a git checkout also gets the license files at the checkout root.
    """
    directory = Path(package['manifest_path']).parent
    source_root = directory
    if package['source'].startswith('git+'):
        while not (source_root / '.cargo-ok').exists():
            source_root = source_root.parent
    found = {path for path in source_root.iterdir() if is_license_file(path)}
    found |= {path for path in directory.rglob('*')
              if is_license_file(path) and not SKIPPED_DIRS & set(path.relative_to(directory).parts[:-1])}
    if package['license_file']:
        found.add(directory / package['license_file'])
    return sorted(found, key=lambda path: str(path.relative_to(source_root)).lower()), source_root


def render(metadata):
    index, texts = [], {}
    for package in linked_packages(metadata):
        label = f"{package['name']} {package['version']}"
        files, source_root = license_files(package)
        index.append(f"{label}: {package['license'] or 'see license file'}"
                     + ('' if files else ' (the crate ships no license file)'))
        for path in files:
            text = path.read_text(encoding='utf-8', errors='replace').strip()
            texts.setdefault(text, []).append(f'{label} ({path.relative_to(source_root)})')
    parts = ['Third-party software linked into bigiris',
             'Generated by scripts/third_party_licenses.py from Cargo.lock; do not edit.',
             'The bigiris source itself is GPL-3.0-or-later (LICENSE); see also NOTICE.',
             '', *index]
    for text, users in texts.items():
        parts += ['', '=' * 72, *(f'Used by {user}' for user in users), '=' * 72, '', text]
    return '\n'.join(parts) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail when the file is out of date')
    args = parser.parse_args()
    metadata = json.loads(subprocess.run(
        ['cargo', 'metadata', '--format-version', '1', '--locked', '--features', FEATURES,
         '--filter-platform', TARGET],
        cwd=ROOT, check=True, capture_output=True, text=True, encoding='utf-8').stdout)
    text = render(metadata)
    if not args.check:
        OUTPUT.write_text(text, encoding='utf-8')
    elif not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != text:
        sys.exit('THIRD_PARTY_LICENSES is out of date: run scripts/third_party_licenses.py')


if __name__ == '__main__':
    main()
