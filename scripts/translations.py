"""Validate all catalogs and regenerate localized integration assets offline."""
import argparse
import ast
import html
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
PO = ROOT / 'data/po'
LANGUAGES = ('bg', 'cs', 'da', 'de', 'el', 'en', 'es', 'et', 'fi', 'fr', 'he', 'hr', 'hu', 'is', 'it', 'ja', 'ko', 'nl', 'no', 'pl', 'pt', 'pt_BR', 'ro', 'ru', 'sk', 'sv', 'tr', 'uk', 'zh')

def n_(text):
    return text

DESKTOP_MESSAGES = (
    n_('Visualizador de imagens'),
    n_('Visualize e converta imagens com integração ao gerenciador de arquivos'),
)

APPSTREAM_SUMMARY = n_('Visualizador e conversor de imagens moderno')

def read_po(path, allow_fuzzy=False):
    """Read singular GNU PO messages without a build dependency on polib."""
    entries = {}
    current = {}
    field = None
    def flush():
        nonlocal current, field
        if current:
            if 'msgid' not in current or 'msgstr' not in current:
                raise ValueError(f'{path}: incomplete PO entry')
            if current['msgid'] in entries:
                raise ValueError(f'{path}: duplicate msgid {current["msgid"]!r}')
            entries[current['msgid']] = current['msgstr']
        current, field = {}, None
    for number, line in enumerate(path.read_text().splitlines(), 1):
        line = line.strip()
        if not line:
            flush()
        elif line.startswith('#'):
            if line.startswith('#,') and 'fuzzy' in line and not allow_fuzzy:
                raise ValueError(f'{path}:{number}: fuzzy translation')
        elif line.startswith(('msgid_plural', 'msgstr[')):
            raise ValueError(f'{path}:{number}: plural entries require extending the validator')
        elif line.startswith(('msgid ', 'msgstr ')):
            field, literal = line.split(' ', 1)
            current[field] = ast.literal_eval(literal)
        elif line.startswith('"') and field:
            current[field] += ast.literal_eval(line)
        else:
            raise ValueError(f'{path}:{number}: unsupported PO syntax')
    flush()
    return entries

def languages():
    found = tuple(line.strip() for line in (PO / 'LINGUAS').read_text().splitlines()
                  if line.strip() and not line.lstrip().startswith('#'))
    if found != LANGUAGES:
        raise ValueError('LINGUAS must match the 29 BigCommunity locales documented in CONTRIBUTING.md')
    return found

def catalogs():
    return {lang: read_po(PO / f'{lang}.po') for lang in languages()}

def check():
    expected = set(read_po(PO / 'bigiris.pot', allow_fuzzy=True)) - {''}
    for lang, entries in catalogs().items():
        if set(entries) - {''} != expected:
            raise ValueError(f'{lang}: catalog does not match POT messages')
        if f'Language: {lang}\n' not in entries.get('', ''):
            raise ValueError(f'{lang}: incorrect Language header')
        for source in expected:
            translated = entries[source]
            if not translated.strip() or '\x00' in translated:
                raise ValueError(f'{lang}: empty or NUL translation: {source!r}')
            placeholders = lambda s: sorted(re.findall(r'\{[A-Za-z_][A-Za-z_0-9]*(?::[^{}]+)?\}', s))
            if placeholders(source) != placeholders(translated):
                raise ValueError(f'{lang}: changed format arguments: {source!r}')
        subprocess.run(['msgfmt', '--check', str(PO / f'{lang}.po'), '-o', '/dev/null'], check=True)
    print(f'{len(LANGUAGES)} catalogs validated; {len(expected)} messages per catalog')

def menu_messages():
    source = (ROOT / 'crates/bigimage-integrations/src/action.rs').read_text()
    return sorted({ast.literal_eval(m) for m in re.findall(r'n_\(("(?:\\.|[^"\\])*")\)', source)})

def generated_assets():
    catalog = catalogs()
    markers = menu_messages()
    lines = ['// SPDX-License-Identifier: GPL-3.0-or-later',
             '// Generated by scripts/translations.py generate; edit data/po/*.po.',
             'pub(super) const CATALOGS: &[(&str, &[(&str, &str)])] = &[']
    quote = lambda text: json.dumps(text, ensure_ascii=False)
    for lang, entries in catalog.items():
        lines.append(f'    ({quote(lang)}, &[')
        for source in markers:
            lines.append(f'        ({quote(source)}, {quote(entries[source])}),')
        lines.append('    ]),')
    lines.append('];')
    path = ROOT / 'crates/bigimage-integrations/src/i18n_data.rs'
    # rustfmt keeps checked-in generated code identical to the formatting gate.
    rust = subprocess.run(['rustfmt', '--edition', '2021'], input='\n'.join(lines)+'\n',
                          capture_output=True, text=True, check=True).stdout
    desktop = (ROOT / 'data/com.biglinux.Iris.desktop').read_text()
    desktop = re.sub(r'^(GenericName|Comment)\[[^]]+\]=.*\n', '', desktop, flags=re.M)
    for key, source in zip(('GenericName', 'Comment'), DESKTOP_MESSAGES):
        localized = ''.join(f'{key}[{lang}]={entries[source]}\n' for lang, entries in catalog.items())
        desktop = re.sub(rf'^{key}=.*\n', lambda m: m[0]+localized, desktop, flags=re.M)
    metainfo = (ROOT / 'data/com.biglinux.Iris.metainfo.xml').read_text()
    metainfo = re.sub(r'^  <summary xml:lang=.*</summary>\n', '', metainfo, flags=re.M)
    localized_summary = ''.join(
        f'  <summary xml:lang="{lang.replace("_", "-")}">{html.escape(entries[APPSTREAM_SUMMARY])}</summary>\n'
        for lang, entries in catalog.items())
    metainfo = re.sub(r'^  <summary>.*</summary>\n', lambda m: m[0]+localized_summary, metainfo, flags=re.M)
    return {path: rust, ROOT / 'data/com.biglinux.Iris.desktop': desktop,
            ROOT / 'data/com.biglinux.Iris.metainfo.xml': metainfo}

def generate(check_only=False):
    for path, text in generated_assets().items():
        if check_only:
            if not path.exists() or path.read_text() != text:
                raise ValueError(f'{path.relative_to(ROOT)}: regenerate with scripts/translations.py generate')
        else:
            path.write_text(text)

def compile_catalogs(destdir):
    check()
    for lang in languages():
        dest = destdir / lang / 'LC_MESSAGES/bigiris.mo'
        dest.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(['msgfmt', '--check', '-o', str(dest), str(PO / f'{lang}.po')], check=True)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=('check', 'generate', 'compile'))
    parser.add_argument('--check-generated', action='store_true')
    parser.add_argument('--destdir', type=Path)
    args = parser.parse_args()
    if args.command == 'compile':
        if args.destdir is None:
            parser.error('compile requires --destdir')
        compile_catalogs(args.destdir)
    elif args.command == 'generate':
        generate(args.check_generated)
    else:
        check()
        if args.check_generated:
            generate(True)

if __name__ == '__main__':
    main()
